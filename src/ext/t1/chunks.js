const KNOWN = new Set(['id', 'track', 'tier', 'tags', 'name', 'hint', 'tip', 'gateTip', 'past', 'now', 'start', 'exit', 'startEra', 'foes', 'guards', 'golems', 'shards', 'arrowPhase', 'bladePhase', 'spikePhase', 'gateHold', 'par', 'solve', 'weight', 'flip', 'join', 'vary', 'extra', 'cam', 'remap', 'roomId']);

let cache = null, cacheN = -1;
/** 쓸 수 있는 조각 전부 (정리된 꼴). T2·T3 조각이 더 들어오면 다시 만든다 */
export function library(EXT) {
  if (cache && cacheN === EXT.chunks.length) return cache;
  const out = [];
  const K = EXT.K;
  if (K && K.ROOMS) for (const r of K.ROOMS) { const m = TUT[r.id]; if (m) out.push(normalize(r, { ...m, id: 'tut-' + r.id, src: 'tut' })); }
  for (const s of SPARE) out.push(normalize(s, { id: 'tut-' + s.id, src: 'tut' }));
  for (const g of GEN) out.push(normalize(g, { src: 't1', weight: g.weight || 1 }));
  for (const ch of EXT.chunks) {
    try {
      const custom = Object.keys(ch).filter(k => !KNOWN.has(k));
      const c = normalize(ch, { src: ch.track || 'ext', weight: ch.weight || 1.6 });
      // 좌표가 든 자기 필드가 있는데 remap이 없으면 이어 붙이지 않는다(뒤집기는 flip:false로 막을 수 있음)
      if (custom.length && ch.join !== true && typeof ch.remap !== 'function') c.join = false;
      if (!c.start || !c.exit) { console.warn('[T1] chunk without start/exit', ch.id); continue; }
      out.push(c);
    } catch (e) { console.error('[T1] bad chunk', ch && ch.id, e); }
  }
  cache = out; cacheN = EXT.chunks.length;
  return out;
}
export const byId = (EXT, id) => library(EXT).find(c => c.id === id) || null;
