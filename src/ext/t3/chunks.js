const tierMark = t => '◆'.repeat(t) + '◇'.repeat(4 - t);
function register() {
  const list = CHUNKS;
  list.forEach((c, n) => {
    EXT.chunks.push(c);
    EXT.rooms[c.id] = EXT.chunkRoom(c, { label: `${tierMark(c.tier)}  ${n + 1} / ${list.length}`, t3next: n + 1 < list.length ? list[n + 1].id : '_end' });
  });
  // 장치별 시험 방 = 그 장치의 tier 1 조각
  for (const [id, cid] of [['t3-seed', 't3-seed1'], ['t3-sluice', 't3-sluice1'], ['t3-mirror', 't3-mirror1'], ['t3-key', 't3-key1'], ['t3-crumble', 't3-crumble1'], ['t3-clock', 't3-clock1'], ['t3-turn', 't3-turn1']]) EXT.rooms[id] = EXT.rooms[cid];
  EXT.rooms['t3-lab'] = EXT.chunkRoom(LAB, { label: 'T3 lab', t3next: list[0].id });
  EXT.rooms['t3-tour'] = EXT.rooms[list[0].id]; // 조각을 차례로 도는 길 (출구로 나가면 다음 조각)
}
register();
// 내 시험 방에서 출구로 나가면 다음 조각으로 (런 모드(T1)가 먼저 고르면 그쪽이 이긴다)
EXT.on('nextRoom', () => { const r = EXT.K && EXT.K.S.room; if (!r || !r.t3next) return undefined; return r.t3next === '_end' ? 'end' : EXT.rooms[r.t3next]; });
